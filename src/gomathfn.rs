const SQRT2_2: f64 = f64::from_bits(0x3fe6a09e667f3bcd); // Sqrt2/2

#[inline(always)]
fn bits(f: f64) -> u64 {
    f.to_bits()
}
#[inline(always)]
fn from_bits(b: u64) -> f64 {
    f64::from_bits(b)
}
/// Go's `<<` on uint64: shifting by >= 64 yields 0.
#[inline(always)]
fn shl(x: u64, s: u64) -> u64 {
    if s >= 64 {
        0
    } else {
        x << s
    }
}
/// Go's `>>` on uint64: shifting by >= 64 yields 0.
#[inline(always)]
fn shr(x: u64, s: u64) -> u64 {
    if s >= 64 {
        0
    } else {
        x >> s
    }
}

pub fn nan() -> f64 {
    from_bits(UVNAN)
}

pub fn inf(sign: i64) -> f64 {
    from_bits(if sign >= 0 { UVINF } else { UVNEGINF })
}

#[allow(clippy::eq_op)]
pub fn is_nan(f: f64) -> bool {
    f != f
}

pub fn is_inf(f: f64, sign: i64) -> bool {
    sign >= 0 && f > MAX_FLOAT64 || sign <= 0 && f < -MAX_FLOAT64
}

pub fn abs(x: f64) -> f64 {
    from_bits(bits(x) & !SIGN_MASK)
}

pub fn copysign(f: f64, sign: f64) -> f64 {
    from_bits(bits(f) & !SIGN_MASK | bits(sign) & SIGN_MASK)
}

pub fn signbit(x: f64) -> bool {
    bits(x) & SIGN_MASK != 0
}

/// math.Sqrt is an intrinsic (correctly rounded) on every platform.
pub fn sqrt(x: f64) -> f64 {
    x.sqrt()
}

fn normalize(x: f64) -> (f64, i64) {
    const SMALLEST_NORMAL: f64 = 2.2250738585072014e-308; // 2**-1022
    if abs(x) < SMALLEST_NORMAL {
        return (x * (1u64 << 52) as f64, -52);
    }
    (x, 0)
}

pub fn frexp(f: f64) -> (f64, i64) {
    if f == 0.0 {
        return (f, 0); // correctly return -0
    }
    if is_inf(f, 0) || is_nan(f) {
        return (f, 0);
    }
    let (f, mut exp) = normalize(f);
    let mut x = bits(f);
    exp += ((x >> SHIFT) & MASK) as i64 - BIAS + 1;
    x &= !(MASK << SHIFT);
    x |= ((-1 + BIAS) as u64) << SHIFT;
    (from_bits(x), exp)
}

pub fn ldexp(frac: f64, exp: i64) -> f64 {
    if frac == 0.0 {
        return frac; // correctly return -0
    }
    if is_inf(frac, 0) || is_nan(frac) {
        return frac;
    }
    let (frac, e) = normalize(frac);
    let mut exp = exp.wrapping_add(e);
    let mut x = bits(frac);
    exp = exp.wrapping_add(((x >> SHIFT) & MASK) as i64 - BIAS);
    if exp < -1075 {
        return copysign(0.0, frac); // underflow
    }
    if exp > 1023 {
        // overflow
        return if frac < 0.0 { inf(-1) } else { inf(1) };
    }
    let mut m = 1.0;
    if exp < -1022 {
        // denormal
        exp += 53;
        m = 1.0 / (1u64 << 53) as f64; // 2**-53
    }
    x &= !(MASK << SHIFT);
    x |= ((exp + BIAS) as u64) << SHIFT;
    m * from_bits(x)
}

fn ilogb_(x: f64) -> i64 {
    let (x, exp) = normalize(x);
    ((bits(x) >> SHIFT) & MASK) as i64 - BIAS + exp
}

pub fn ilogb(x: f64) -> i64 {
    if x == 0.0 {
        return i32::MIN as i64;
    }
    if is_nan(x) || is_inf(x, 0) {
        return i32::MAX as i64;
    }
    ilogb_(x)
}

pub fn logb(x: f64) -> f64 {
    if x == 0.0 {
        return inf(-1);
    }
    if is_inf(x, 0) {
        return inf(1);
    }
    if is_nan(x) {
        return x;
    }
    ilogb_(x) as f64
}

pub fn dim(x: f64, y: f64) -> f64 {
    let v = x - y;
    if v <= 0.0 {
        return 0.0;
    }
    v
}

/// dim.go `max` (arm64's assembly has the same semantics).
pub fn max(x: f64, y: f64) -> f64 {
    if is_inf(x, 1) || is_inf(y, 1) {
        return inf(1);
    }
    if is_nan(x) || is_nan(y) {
        return nan();
    }
    if x == 0.0 && x == y {
        return if signbit(x) { y } else { x };
    }
    if x > y {
        x
    } else {
        y
    }
}

/// dim.go `min` (arm64's assembly has the same semantics).
pub fn min(x: f64, y: f64) -> f64 {
    if is_inf(x, -1) || is_inf(y, -1) {
        return inf(-1);
    }
    if is_nan(x) || is_nan(y) {
        return nan();
    }
    if x == 0.0 && x == y {
        return if signbit(x) { x } else { y };
    }
    if x < y {
        x
    } else {
        y
    }
}

pub fn nextafter(x: f64, y: f64) -> f64 {
    if is_nan(x) || is_nan(y) {
        nan()
    } else if x == y {
        x
    } else if x == 0.0 {
        copysign(from_bits(1), y)
    } else if (y > x) == (x > 0.0) {
        from_bits(bits(x).wrapping_add(1))
    } else {
        from_bits(bits(x).wrapping_sub(1))
    }
}

pub fn pow10(n: i64) -> f64 {
    const TAB: [f64; 32] = [
        1e00, 1e01, 1e02, 1e03, 1e04, 1e05, 1e06, 1e07, 1e08, 1e09, 1e10, 1e11, 1e12, 1e13, 1e14,
        1e15, 1e16, 1e17, 1e18, 1e19, 1e20, 1e21, 1e22, 1e23, 1e24, 1e25, 1e26, 1e27, 1e28, 1e29,
        1e30, 1e31,
    ];
    const POS32: [f64; 10] = [1e00, 1e32, 1e64, 1e96, 1e128, 1e160, 1e192, 1e224, 1e256, 1e288];
    const NEG32: [f64; 11] = [
        1e-00, 1e-32, 1e-64, 1e-96, 1e-128, 1e-160, 1e-192, 1e-224, 1e-256, 1e-288, 1e-320,
    ];
    if (0..=308).contains(&n) {
        return POS32[(n / 32) as usize] * TAB[(n % 32) as usize];
    }
    if (-323..=0).contains(&n) {
        let m = -n;
        return NEG32[(m / 32) as usize] / TAB[(m % 32) as usize];
    }
    if n > 0 {
        return inf(1);
    }
    0.0
}

