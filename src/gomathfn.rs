const UVNAN: u64 = 0x7FF8000000000001;
const UVINF: u64 = 0x7FF0000000000000;
const UVNEGINF: u64 = 0xFFF0000000000000;
const MASK: u64 = 0x7FF;
const SHIFT: u32 = 64 - 11 - 1;
const BIAS: i64 = 1023;
const SIGN_MASK: u64 = 1 << 63;
const FRAC_MASK: u64 = (1 << SHIFT) - 1;

const MAX_FLOAT64: f64 = f64::MAX;
const PI: f64 = f64::from_bits(0x400921fb54442d18);
const PI_2: f64 = f64::from_bits(0x3ff921fb54442d18); // Pi/2
const PI_4: f64 = f64::from_bits(0x3fe921fb54442d18); // Pi/4
const PI3_4: f64 = f64::from_bits(0x4002d97c7f3321d2); // 3*Pi/4
const FOUR_OVER_PI: f64 = f64::from_bits(0x3ff45f306dc9c883); // 4/Pi
