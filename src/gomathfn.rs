impl<const FMA: bool, const ASM: bool> GoMath<FMA, ASM> {
    // -- fused multiply-add sites ------------------------------------------

    /// `a + x*y` (FMADDD when fused).
    #[inline(always)]
    fn fa(a: f64, x: f64, y: f64) -> f64 {
        if FMA {
            x.mul_add(y, a)
        } else {
            a + x * y
        }
    }
    /// `a - x*y` (FMSUBD when fused).
    #[inline(always)]
    fn fs(a: f64, x: f64, y: f64) -> f64 {
        if FMA {
            (-x).mul_add(y, a)
        } else {
            a - x * y
        }
    }
    /// `x*y - a` (FNMSUBD when fused).
    #[inline(always)]
    fn fr(a: f64, x: f64, y: f64) -> f64 {
        if FMA {
            x.mul_add(y, -a)
        } else {
            x * y - a
        }
    }
    /// `-(x*y) - a` (FNMADDD when fused).
    #[inline(always)]
    fn fnm(a: f64, x: f64, y: f64) -> f64 {
        if FMA {
            (-x).mul_add(y, -a)
        } else {
            -(x * y) - a
        }
    }
    /// Horner evaluation, coefficients from the highest degree down:
    /// `c[n] + z*(c[n-1] + z*(... + z*c[0]))`, each step one fused site.
    #[inline(always)]
    fn poly(z: f64, c: &[f64]) -> f64 {
        let mut p = c[0];
        for &ci in &c[1..] {
            p = Self::fa(ci, z, p);
        }
        p
    }

    // -- floor.go / modf.go -------------------------------------------------

    pub fn modf(f: f64) -> (f64, f64) {
        if ASM {
            // modf_arm64.s
            let i = f.trunc();
            let fr = from_bits(bits(f - i) | (bits(f) & SIGN_MASK));
            return (i, fr);
        }
        if f < 1.0 {
            if f < 0.0 {
                let (i, fr) = Self::modf(-f);
                return (-i, -fr);
            }
            if f == 0.0 {
                return (f, f); // Return -0, -0 when f == -0
            }
            return (0.0, f);
        }
        let mut x = bits(f);
        let e = ((x >> SHIFT) & MASK).wrapping_sub(BIAS as u64);
        if e < 64 - 12 {
            x &= !((1u64 << (64 - 12 - e)) - 1);
        }
        let i = from_bits(x);
        (i, f - i)
    }

    pub fn floor(x: f64) -> f64 {
        if ASM {
            return x.floor(); // FRINTMD
        }
        if x == 0.0 || is_nan(x) || is_inf(x, 0) {
            return x;
        }
        if x < 0.0 {
            let (mut d, fract) = Self::modf(-x);
            if fract != 0.0 {
                d += 1.0;
            }
            return -d;
        }
        Self::modf(x).0
    }

    pub fn ceil(x: f64) -> f64 {
        if ASM {
            return x.ceil(); // FRINTPD
        }
        -Self::floor(-x)
    }

    pub fn trunc(x: f64) -> f64 {
        if ASM {
            return x.trunc(); // FRINTZD
        }
        if x == 0.0 || is_nan(x) || is_inf(x, 0) {
            return x;
        }
        Self::modf(x).0
    }

    // -- sin.go / tan.go / sincos.go ----------------------------------------

    /// `x - y*Pi/4` in extended precision (three fused sites).
    #[inline(always)]
    fn reduce(x: f64, y: f64) -> f64 {
        Self::fs(Self::fs(Self::fs(x, y, PI4A), y, PI4B), y, PI4C)
    }
    #[inline(always)]
    fn sin_kernel(z: f64, zz: f64) -> f64 {
        Self::fa(z, z * zz, Self::poly(zz, &SIN))
    }
    #[inline(always)]
    fn cos_kernel(zz: f64) -> f64 {
        Self::fa(Self::fs(1.0, 0.5, zz), zz * zz, Self::poly(zz, &COS))
    }

    pub fn cos(x: f64) -> f64 {
        if is_nan(x) || is_inf(x, 0) {
            return nan();
        }
        let mut sign = false;
        let x = abs(x);
        let (mut j, z);
        if x >= REDUCE_THRESHOLD {
            (j, z) = trig_reduce(x);
        } else {
            j = (x * FOUR_OVER_PI) as u64;
            let mut y = j as f64;
            if j & 1 == 1 {
                j += 1;
                y += 1.0;
            }
            j &= 7;
            z = Self::reduce(x, y);
        }
        if j > 3 {
            j -= 4;
            sign = !sign;
        }
        if j > 1 {
            sign = !sign;
        }
        let zz = z * z;
        let y = if j == 1 || j == 2 { Self::sin_kernel(z, zz) } else { Self::cos_kernel(zz) };
        if sign {
            -y
        } else {
            y
        }
    }

    pub fn sin(x: f64) -> f64 {
        if x == 0.0 || is_nan(x) {
            return x;
        }
        if is_inf(x, 0) {
            return nan();
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        let (mut j, z);
        if x >= REDUCE_THRESHOLD {
            (j, z) = trig_reduce(x);
        } else {
            j = (x * FOUR_OVER_PI) as u64;
            let mut y = j as f64;
            if j & 1 == 1 {
                j += 1;
                y += 1.0;
            }
            j &= 7;
            z = Self::reduce(x, y);
        }
        if j > 3 {
            sign = !sign;
            j -= 4;
        }
        let zz = z * z;
        let y = if j == 1 || j == 2 { Self::cos_kernel(zz) } else { Self::sin_kernel(z, zz) };
        if sign {
            -y
        } else {
            y
        }
    }

    pub fn sincos(x: f64) -> (f64, f64) {
        if x == 0.0 {
            return (x, 1.0);
        }
        if is_nan(x) || is_inf(x, 0) {
            return (nan(), nan());
        }
        let (mut sin_sign, mut cos_sign) = (false, false);
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sin_sign = true;
        }
        let (mut j, z);
        if x >= REDUCE_THRESHOLD {
            (j, z) = trig_reduce(x);
        } else {
            j = (x * FOUR_OVER_PI) as u64;
            let mut y = j as f64;
            if j & 1 == 1 {
                j += 1;
                y += 1.0;
            }
            j &= 7;
            z = Self::reduce(x, y);
        }
        if j > 3 {
            j -= 4;
            sin_sign = !sin_sign;
            cos_sign = !cos_sign;
        }
        if j > 1 {
            cos_sign = !cos_sign;
        }
        let zz = z * z;
        let mut c = Self::cos_kernel(zz);
        let mut s = Self::sin_kernel(z, zz);
        if j == 1 || j == 2 {
            std::mem::swap(&mut s, &mut c);
        }
        if cos_sign {
            c = -c;
        }
        if sin_sign {
            s = -s;
        }
        (s, c)
    }

    pub fn tan(x: f64) -> f64 {
        const TP: [f64; 3] = [
            -1.30936939181383777646e4,
            1.15351664838587416140e6,
            -1.79565251976484877988e7,
        ];
        const TQ: [f64; 5] = [
            1.00000000000000000000e0,
            1.36812963470692954678e4,
            -1.32089234440210967447e6,
            2.50083801823357915839e7,
            -5.38695755929454629881e7,
        ];
        if x == 0.0 || is_nan(x) {
            return x;
        }
        if is_inf(x, 0) {
            return nan();
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        let (j, z);
        if x >= REDUCE_THRESHOLD {
            (j, z) = trig_reduce(x);
        } else {
            let mut jj = (x * FOUR_OVER_PI) as u64;
            let mut y = jj as f64;
            if jj & 1 == 1 {
                jj += 1;
                y += 1.0;
            }
            j = jj;
            z = Self::reduce(x, y);
        }
        let zz = z * z;
        let mut y = if zz > 1e-14 {
            let num = zz * Self::poly(zz, &TP);
            let mut den = Self::fa(TQ[1], z, z); // zz + Q1
            den = Self::fa(TQ[2], zz, den);
            den = Self::fa(TQ[3], zz, den);
            den = Self::fa(TQ[4], zz, den);
            Self::fa(z, num / den, z)
        } else {
            z
        };
        if j & 2 == 2 {
            y = -1.0 / y;
        }
        if sign {
            y = -y;
        }
        y
    }

    // -- atan.go / asin.go / atan2.go ---------------------------------------

    fn xatan(x: f64) -> f64 {
        const P: [f64; 5] = [
            -8.750608600031904122785e-01,
            -1.615753718733365076637e+01,
            -7.500855792314704667340e+01,
            -1.228866684490136173410e+02,
            -6.485021904942025371773e+01,
        ];
        const Q: [f64; 5] = [
            2.485846490142306297962e+01,
            1.650270098316988542046e+02,
            4.328810604912902668951e+02,
            4.853903996359136964868e+02,
            1.945506571482613964425e+02,
        ];
        let z = x * x;
        let num = z * Self::poly(z, &P);
        let mut den = Self::fa(Q[0], x, x); // z + Q0
        den = Self::fa(Q[1], z, den);
        den = Self::fa(Q[2], z, den);
        den = Self::fa(Q[3], z, den);
        den = Self::fa(Q[4], z, den);
        let z = num / den;
        Self::fa(x, x, z) // x*z + x
    }

    fn satan(x: f64) -> f64 {
        const MOREBITS: f64 = 6.123233995736765886130e-17;
        const HALF_MOREBITS: f64 = f64::from_bits(0x3c81a62633145c07);
        const TAN3PIO8: f64 = 2.41421356237309504880;
        if x <= 0.66 {
            return Self::xatan(x);
        }
        if x > TAN3PIO8 {
            return PI_2 - Self::xatan(1.0 / x) + MOREBITS;
        }
        PI_4 + Self::xatan((x - 1.0) / (x + 1.0)) + HALF_MOREBITS
    }

    pub fn atan(x: f64) -> f64 {
        if x == 0.0 {
            return x;
        }
        if x > 0.0 {
            return Self::satan(x);
        }
        -Self::satan(-x)
    }

    pub fn asin(x: f64) -> f64 {
        if x == 0.0 {
            return x;
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        if x > 1.0 {
            return nan();
        }
        let mut temp = sqrt(Self::fs(1.0, x, x));
        if x > 0.7 {
            temp = PI_2 - Self::satan(temp / x);
        } else {
            temp = Self::satan(x / temp);
        }
        if sign {
            temp = -temp;
        }
        temp
    }

    pub fn acos(x: f64) -> f64 {
        PI_2 - Self::asin(x)
    }

    pub fn atan2(y: f64, x: f64) -> f64 {
        if is_nan(y) || is_nan(x) {
            return nan();
        }
        if y == 0.0 {
            if x >= 0.0 && !signbit(x) {
                return copysign(0.0, y);
            }
            return copysign(PI, y);
        }
        if x == 0.0 {
            return copysign(PI_2, y);
        }
        if is_inf(x, 0) {
            if is_inf(x, 1) {
                if is_inf(y, 0) {
                    return copysign(PI_4, y);
                }
                return copysign(0.0, y);
            }
            if is_inf(y, 0) {
                return copysign(PI3_4, y);
            }
            return copysign(PI, y);
        }
        if is_inf(y, 0) {
            return copysign(PI_2, y);
        }
        let q = Self::atan(y / x);
        if x < 0.0 {
            if q <= 0.0 {
                return q + PI;
            }
            return q - PI;
        }
        q
    }

    // -- acosh.go / asinh.go / atanh.go -------------------------------------

    pub fn acosh(x: f64) -> f64 {
        const LARGE: f64 = (1u64 << 28) as f64;
        if x < 1.0 || is_nan(x) {
            return nan();
        }
        if x == 1.0 {
            return 0.0;
        }
        if x >= LARGE {
            return Self::log(x) + LN2;
        }
        if x > 2.0 {
            return Self::log(x + x - 1.0 / (x + sqrt(Self::fr(1.0, x, x))));
        }
        let t = x - 1.0;
        Self::log1p(t + sqrt(Self::fa(t + t, t, t)))
    }

    pub fn asinh(x: f64) -> f64 {
        const NEAR_ZERO: f64 = 1.0 / (1u64 << 28) as f64;
        const LARGE: f64 = (1u64 << 28) as f64;
        if is_nan(x) || is_inf(x, 0) {
            return x;
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        let mut temp = if x > LARGE {
            Self::log(x) + LN2
        } else if x > 2.0 {
            Self::log(x + x + 1.0 / (sqrt(Self::fa(1.0, x, x)) + x))
        } else if x < NEAR_ZERO {
            x
        } else {
            Self::log1p(x + x * x / (1.0 + sqrt(Self::fa(1.0, x, x))))
        };
        if sign {
            temp = -temp;
        }
        temp
    }

    pub fn atanh(x: f64) -> f64 {
        const NEAR_ZERO: f64 = 1.0 / (1u64 << 28) as f64;
        if x < -1.0 || x > 1.0 || is_nan(x) {
            return nan();
        }
        if x == 1.0 {
            return inf(1);
        }
        if x == -1.0 {
            return inf(-1);
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        let mut temp = if x < NEAR_ZERO {
            x
        } else if x < 0.5 {
            let t = x + x;
            0.5 * Self::log1p(t + t * x / (1.0 - x))
        } else {
            0.5 * Self::log1p((x + x) / (1.0 - x))
        };
        if sign {
            temp = -temp;
        }
        temp
    }

    // -- exp.go / exp_arm64.s ----------------------------------------------

    pub fn exp(x: f64) -> f64 {
        if ASM {
            return Self::exp_arm64(x);
        }
        const OVERFLOW: f64 = 7.09782712893383973096e+02;
        const UNDERFLOW: f64 = -7.45133219101941108420e+02;
        const NEAR_ZERO: f64 = 1.0 / (1u64 << 28) as f64;
        if is_nan(x) || is_inf(x, 1) {
            return x;
        }
        if is_inf(x, -1) {
            return 0.0;
        }
        if x > OVERFLOW {
            return inf(1);
        }
        if x < UNDERFLOW {
            return 0.0;
        }
        if -NEAR_ZERO < x && x < NEAR_ZERO {
            return 1.0 + x;
        }
        let k: i64 = if x < 0.0 {
            Self::fr(0.5, LOG2E, x) as i64
        } else if x > 0.0 {
            Self::fa(0.5, LOG2E, x) as i64
        } else {
            0
        };
        let kf = k as f64;
        let hi = Self::fs(x, kf, LN2HI);
        let lo = kf * LN2LO;
        Self::expmulti(hi, lo, k)
    }

    pub fn exp2(x: f64) -> f64 {
        if ASM {
            return Self::exp2_arm64(x);
        }
        const OVERFLOW: f64 = 1.0239999999999999e+03;
        const UNDERFLOW: f64 = -1.0740e+03;
        if is_nan(x) || is_inf(x, 1) {
            return x;
        }
        if is_inf(x, -1) {
            return 0.0;
        }
        if x > OVERFLOW {
            return inf(1);
        }
        if x < UNDERFLOW {
            return 0.0;
        }
        let k: i64 = if x > 0.0 {
            (x + 0.5) as i64
        } else if x < 0.0 {
            (x - 0.5) as i64
        } else {
            0
        };
        let t = x - k as f64;
        let hi = t * LN2HI;
        let lo = -(t * LN2LO);
        Self::expmulti(hi, lo, k)
    }

    fn expmulti(hi: f64, lo: f64, k: i64) -> f64 {
        let r = hi - lo;
        let t = r * r;
        let c = Self::fs(r, t, Self::poly(t, &EXP_P));
        let y = 1.0 - ((lo - (r * c) / (2.0 - c)) - hi);
        ldexp(y, k)
    }

    /// The tail shared by archExp and archExp2 in exp_arm64.s.
    fn exp_arm64_tail(hi: f64, lo: f64, k: i64) -> f64 {
        let r = hi - lo;
        let t = r * r;
        let mut p = EXP_P[0];
        for &c in &EXP_P[1..] {
            p = t.mul_add(p, c);
        }
        let c = (-t).mul_add(p, r);
        let y = 1.0 - ((lo - (r * c) / (2.0 - c)) - hi);
        // inline Ldexp(y, k) without range checks
        let yb = bits(y);
        let frac = yb & FRAC_MASK;
        let mut e = (yb >> 52) as i64 + k;
        let mut m = 1.0;
        if e < 1 {
            e += 52;
            m = f64::from_bits(0x3cb0000000000000); // 2**-52
        }
        from_bits(((e as u64) << 52) | frac) * m
    }

    fn exp_arm64(x: f64) -> f64 {
        const OVERFLOW: f64 = 7.09782712893383973096e+02;
        const UNDERFLOW: f64 = -7.45133219101941108420e+02;
        const NEAR_ZERO: f64 = f64::from_bits(0x3e30000000000000); // 2**-28
        if is_nan(x) {
            return x;
        }
        if x > OVERFLOW {
            return inf(1);
        }
        if x < UNDERFLOW {
            return 0.0;
        }
        if abs(x) < NEAR_ZERO {
            return 1.0 + x;
        }
        let kf = if x < 0.0 { LOG2E.mul_add(x, -0.5) } else { LOG2E.mul_add(x, 0.5) };
        let k = kf as i64;
        let kf = k as f64;
        let hi = (-kf).mul_add(LN2HI, x);
        let lo = kf * LN2LO;
        Self::exp_arm64_tail(hi, lo, k)
    }

    fn exp2_arm64(x: f64) -> f64 {
        const OVERFLOW: f64 = 1.0239999999999999e+03;
        const UNDERFLOW: f64 = -1.0740e+03;
        if is_nan(x) {
            return x;
        }
        if x > OVERFLOW {
            return inf(1);
        }
        if x < UNDERFLOW {
            return 0.0;
        }
        let kf = if x < 0.0 { x - 0.5 } else { x + 0.5 };
        let k = kf as i64;
        let t = x - k as f64;
        let hi = t * LN2HI;
        let lo = -(t * LN2LO);
        Self::exp_arm64_tail(hi, lo, k)
    }

    // -- expm1.go ------------------------------------------------------------

    pub fn expm1(x: f64) -> f64 {
        const OTHRESHOLD: f64 = 7.09782712893383973096e+02;
        const LN2X56: f64 = 3.88162421113569373274e+01;
        const LN2HALFX3: f64 = 1.03972077083991796413e+00;
        const LN2HALF: f64 = 3.46573590279972654709e-01;
        const INVLN2: f64 = 1.44269504088896338700e+00;
        const TINY: f64 = 1.0 / (1u64 << 54) as f64;
        const Q: [f64; 6] = [
            -2.01099218183624371326e-07, // Q5
            4.00821782732936239552e-06,  // Q4
            -7.93650757867487942473e-05, // Q3
            1.58730158725481460165e-03,  // Q2
            -3.33333333333331316428e-02, // Q1
            1.0,
        ];
        if is_inf(x, 1) || is_nan(x) {
            return x;
        }
        if is_inf(x, -1) {
            return -1.0;
        }
        let mut x = x;
        let mut absx = x;
        let mut sign = false;
        if x < 0.0 {
            absx = -absx;
            sign = true;
        }
        if absx >= LN2X56 {
            if sign {
                return -1.0;
            }
            if absx >= OTHRESHOLD {
                return inf(1);
            }
        }
        let mut c = 0.0;
        let k: i64;
        if absx > LN2HALF {
            let (hi, lo);
            if absx < LN2HALFX3 {
                if !sign {
                    hi = x - LN2HI;
                    lo = LN2LO;
                    k = 1;
                } else {
                    hi = x + LN2HI;
                    lo = -LN2LO;
                    k = -1;
                }
            } else {
                k = if !sign {
                    Self::fa(0.5, INVLN2, x) as i64
                } else {
                    Self::fr(0.5, INVLN2, x) as i64
                };
                let t = k as f64;
                hi = Self::fs(x, t, LN2HI);
                lo = t * LN2LO;
            }
            x = hi - lo;
            c = (hi - x) - lo;
        } else if absx < TINY {
            return x;
        } else {
            k = 0;
        }
        let hfx = 0.5 * x;
        let hxs = x * hfx;
        let r1 = Self::poly(hxs, &Q);
        let t = Self::fs(3.0, r1, hfx);
        let q = (r1 - t) / Self::fs(6.0, x, t);
        let e = hxs * q;
        if k == 0 {
            return x - Self::fs(x * e, x, hfx); // x - (x*e - hxs)
        }
        let mut e = Self::fr(c, x, Self::fr(c, hxs, q)); // x*(e-c) - c
        e = Self::fs(e, x, hfx); // e -= hxs
        if k == -1 {
            return Self::fr(0.5, x - e, 0.5); // 0.5*(x-e) - 0.5
        }
        if k == 1 {
            if x < -0.25 {
                return -2.0 * (e - (x + 0.5));
            }
            return 1.0 + 2.0 * (x - e);
        }
        if k <= -2 || k > 56 {
            let y = 1.0 - (e - x);
            let y = from_bits(bits(y).wrapping_add((k as u64) << 52));
            return y - 1.0;
        }
        if k < 20 {
            let t = from_bits(0x3ff0000000000000 - (0x20000000000000u64 >> k)); // 1-2**-k
            let y = t - (e - x);
            return from_bits(bits(y).wrapping_add((k as u64) << 52));
        }
        let t = from_bits(((0x3ff - k) as u64) << 52); // 2**-k
        let mut y = x - (e + t);
        y += 1.0;
        from_bits(bits(y).wrapping_add((k as u64) << 52))
    }

    // -- log.go / log10.go / log1p.go ---------------------------------------

    pub fn log(x: f64) -> f64 {
        const L: [f64; 7] = [
            6.666666666666735130e-01,
            3.999999999940941908e-01,
            2.857142874366239149e-01,
            2.222219843214978396e-01,
            1.818357216161805012e-01,
            1.531383769920937332e-01,
            1.479819860511658591e-01,
        ];
        if is_nan(x) || is_inf(x, 1) {
            return x;
        }
        if x < 0.0 {
            return nan();
        }
        if x == 0.0 {
            return inf(-1);
        }
        let (mut f1, mut ki) = frexp(x);
        if f1 < SQRT2_2 {
            f1 *= 2.0;
            ki -= 1;
        }
        let f = f1 - 1.0;
        let k = ki as f64;
        let s = f / (2.0 + f);
        let s2 = s * s;
        let s4 = s2 * s2;
        let p1 = Self::poly(s4, &[L[6], L[4], L[2], L[0]]); // t1 = s2*p1
        let t2 = s4 * Self::poly(s4, &[L[5], L[3], L[1]]);
        let r = Self::fa(t2, s2, p1); // R := t1 + t2
        let hf = 0.5 * f; // hfsq := hf*f
        let inner = Self::fa(k * LN2LO, s, Self::fa(r, hf, f)); // s*(hfsq+R) + k*Ln2Lo
        let a = Self::fr(inner, hf, f) - f; // (hfsq - inner) - f
        Self::fr(a, k, LN2HI) // k*Ln2Hi - a
    }

    pub fn log10(x: f64) -> f64 {
        Self::log(x) * INV_LN10
    }

    pub fn log2(x: f64) -> f64 {
        let (frac, exp) = frexp(x);
        if frac == 0.5 {
            return (exp - 1) as f64;
        }
        Self::fa(exp as f64, Self::log(frac), INV_LN2)
    }

    pub fn log1p(x: f64) -> f64 {
        const SQRT2M1: f64 = 4.142135623730950488017e-01;
        const SQRT2HALFM1: f64 = -2.928932188134524755992e-01;
        const SMALL: f64 = 1.0 / (1u64 << 29) as f64;
        const TINY: f64 = 1.0 / (1u64 << 54) as f64;
        const TWO53: f64 = (1u64 << 53) as f64;
        const LP: [f64; 7] = [
            1.479819860511658591e-01, // Lp7
            1.531383769920937332e-01, // Lp6
            1.818357216161805012e-01, // Lp5
            2.222219843214978396e-01, // Lp4
            2.857142874366239149e-01, // Lp3
            3.999999999940941908e-01, // Lp2
            6.666666666666735130e-01, // Lp1
        ];
        if x < -1.0 || is_nan(x) {
            return nan();
        }
        if x == -1.0 {
            return inf(-1);
        }
        if is_inf(x, 1) {
            return inf(1);
        }
        let absx = abs(x);
        let mut f = 0.0;
        let mut iu: u64 = 0;
        let mut k: i64 = 1;
        if absx < SQRT2M1 {
            if absx < SMALL {
                if absx < TINY {
                    return x;
                }
                return Self::fs(x, x * x, 0.5); // x - x*x*0.5
            }
            if x > SQRT2HALFM1 {
                k = 0;
                f = x;
                iu = 1;
            }
        }
        let mut c = 0.0;
        if k != 0 {
            let mut u;
            if absx < TWO53 {
                u = 1.0 + x;
                iu = bits(u);
                k = (iu >> 52).wrapping_sub(1023) as i64;
                if k > 0 {
                    c = 1.0 - (u - x);
                } else {
                    c = x - (u - 1.0);
                }
                c /= u;
            } else {
                u = x;
                iu = bits(u);
                k = (iu >> 52).wrapping_sub(1023) as i64;
                c = 0.0;
            }
            iu &= 0x000fffffffffffff;
            if iu < 0x0006a09e667f3bcd {
                u = from_bits(iu | 0x3ff0000000000000);
            } else {
                k += 1;
                u = from_bits(iu | 0x3fe0000000000000);
                iu = (0x0010000000000000 - iu) >> 2;
            }
            f = u - 1.0;
        }
        let hf = 0.5 * f;
        let hfsq = hf * f;
        let kf = k as f64;
        if iu == 0 {
            if f == 0.0 {
                if k == 0 {
                    return 0.0;
                }
                c = Self::fa(c, kf, LN2LO);
                return Self::fa(c, kf, LN2HI);
            }
            let w = Self::fs(1.0, 0.66666666666666666, f); // R = hfsq*w
            if k == 0 {
                return Self::fs(f, hfsq, w); // f - R
            }
            let b = Self::fr(Self::fa(c, kf, LN2LO), hfsq, w) - f;
            return Self::fr(b, kf, LN2HI);
        }
        let s = f / (2.0 + f);
        let z = s * s;
        let r = z * Self::poly(z, &LP);
        let hpr = Self::fa(r, hf, f); // hfsq + R
        if k == 0 {
            return f - Self::fs(hfsq, s, hpr); // f - (hfsq - s*(hfsq+R))
        }
        let b = Self::fa(Self::fa(c, kf, LN2LO), s, hpr); // s*(hfsq+R) + (k*Ln2Lo + c)
        let d = Self::fr(b, hf, f) - f; // (hfsq - b) - f
        Self::fr(d, kf, LN2HI)
    }

    // -- pow.go --------------------------------------------------------------

    fn is_odd_int(x: f64) -> bool {
        if abs(x) >= (1u64 << 53) as f64 {
            return false;
        }
        let (xi, xf) = Self::modf(x);
        xf == 0.0 && (xi as i64) & 1 == 1
    }

    pub fn pow(x: f64, y: f64) -> f64 {
        if y == 0.0 || x == 1.0 {
            return 1.0;
        }
        if y == 1.0 {
            return x;
        }
        if is_nan(x) || is_nan(y) {
            return nan();
        }
        if x == 0.0 {
            if y < 0.0 {
                if signbit(x) && Self::is_odd_int(y) {
                    return inf(-1);
                }
                return inf(1);
            }
            if y > 0.0 {
                if signbit(x) && Self::is_odd_int(y) {
                    return x;
                }
                return 0.0;
            }
        } else if is_inf(y, 0) {
            if x == -1.0 {
                return 1.0;
            }
            if (abs(x) < 1.0) == is_inf(y, 1) {
                return 0.0;
            }
            return inf(1);
        } else if is_inf(x, 0) {
            if is_inf(x, -1) {
                return Self::pow(1.0 / x, -y); // Pow(-0, -y)
            }
            if y < 0.0 {
                return 0.0;
            }
            if y > 0.0 {
                return inf(1);
            }
        } else if y == 0.5 {
            return sqrt(x);
        } else if y == -0.5 {
            return 1.0 / sqrt(x);
        }

        let (mut yi, mut yf) = Self::modf(abs(y));
        if yf != 0.0 && x < 0.0 {
            return nan();
        }
        if yi >= 9.223372036854775808e18 {
            // yi is a large even int; result is 0, 1 or Inf
            if x == -1.0 {
                return 1.0;
            }
            if (abs(x) < 1.0) == (y > 0.0) {
                return 0.0;
            }
            return inf(1);
        }
        let mut a1 = 1.0;
        let mut ae: i64 = 0;
        if yf != 0.0 {
            if yf > 0.5 {
                yf -= 1.0;
                yi += 1.0;
            }
            a1 = Self::exp(yf * Self::log(x));
        }
        let (mut x1, mut xe) = frexp(x);
        let mut i = yi as i64;
        while i != 0 {
            if xe < -(1 << 12) || (1 << 12) < xe {
                ae += xe;
                break;
            }
            if i & 1 == 1 {
                a1 *= x1;
                ae += xe;
            }
            let sq = x1 * x1;
            xe <<= 1;
            if sq < 0.5 {
                x1 = Self::fa(sq, x1, x1); // x1 += x1
                xe -= 1;
            } else {
                x1 = sq;
            }
            i >>= 1;
        }
        if y < 0.0 {
            a1 = 1.0 / a1;
            ae = -ae;
        }
        ldexp(a1, ae)
    }

    // -- mod.go / remainder.go -----------------------------------------------

    pub fn fmod(x: f64, y: f64) -> f64 {
        if y == 0.0 || is_inf(x, 0) || is_nan(x) || is_nan(y) {
            return nan();
        }
        let y = abs(y);
        let (yfr, yexp) = frexp(y);
        let mut r = x;
        if x < 0.0 {
            r = -x;
        }
        while r >= y {
            let (rfr, mut rexp) = frexp(r);
            if rfr < yfr {
                rexp -= 1;
            }
            r -= ldexp(y, rexp - yexp);
        }
        if x < 0.0 {
            r = -r;
        }
        r
    }

    pub fn remainder(x: f64, y: f64) -> f64 {
        const TINY: f64 = 4.45014771701440276618e-308;
        const HALF_MAX: f64 = f64::from_bits(0x7fdfffffffffffff); // MaxFloat64/2
        if is_nan(x) || is_nan(y) || is_inf(x, 0) || y == 0.0 {
            return nan();
        }
        if is_inf(y, 0) {
            return x;
        }
        let mut x = x;
        let mut y = y;
        let mut sign = false;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        if y < 0.0 {
            y = -y;
        }
        if x == y {
            if sign {
                return -0.0;
            }
            return 0.0;
        }
        if y <= HALF_MAX {
            x = Self::fmod(x, y + y);
        }
        if y < TINY {
            if x + x > y {
                x -= y;
                if x + x >= y {
                    x -= y;
                }
            }
        } else {
            let y_half = 0.5 * y;
            if x > y_half {
                x -= y;
                if x >= y_half {
                    x -= y;
                }
            }
        }
        if sign {
            x = -x;
        }
        x
    }

    // -- sinh.go / tanh.go ---------------------------------------------------

    pub fn sinh(x: f64) -> f64 {
        const P: [f64; 4] = [
            -0.2630563213397497062819489e+2,   // P3
            -0.2894211355989563807284660366e+4, // P2
            -0.8991272022039509355398013511e+5, // P1
            -0.6307673640497716991184787251e+6, // P0
        ];
        const Q0: f64 = -0.6307673640497716991212077277e+6;
        const Q1: f64 = 0.1521517378790019070696485176e+5;
        const Q2: f64 = -0.173678953558233699533450911e+3;
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        let mut temp = if x > 21.0 {
            Self::exp(x) * 0.5
        } else if x > 0.5 {
            let ex = Self::exp(x);
            (ex - 1.0 / ex) * 0.5
        } else {
            let sq = x * x;
            let num = Self::poly(sq, &P) * x;
            let mut den = Self::fa(Q2, x, x); // sq + Q2
            den = Self::fa(Q1, sq, den);
            den = Self::fa(Q0, sq, den);
            num / den
        };
        if sign {
            temp = -temp;
        }
        temp
    }

    pub fn cosh(x: f64) -> f64 {
        let x = abs(x);
        if x > 21.0 {
            return Self::exp(x) * 0.5;
        }
        let ex = Self::exp(x);
        (ex + 1.0 / ex) * 0.5
    }

    pub fn tanh(x: f64) -> f64 {
        const P: [f64; 3] = [
            -9.64399179425052238628e-1,
            -9.92877231001918586564e1,
            -1.61468768441708447952e3,
        ];
        const Q: [f64; 3] = [
            1.12811678491632931402e2,
            2.23548839060100448583e3,
            4.84406305325125486048e3,
        ];
        const HALF_MAXLOG: f64 = f64::from_bits(0x404601e678fc457b); // 0.5*MAXLOG
        let mut z = abs(x);
        if z > HALF_MAXLOG {
            if x < 0.0 {
                return -1.0;
            }
            return 1.0;
        } else if z >= 0.625 {
            let s = Self::exp(z + z);
            z = 1.0 - 2.0 / (s + 1.0);
            if x < 0.0 {
                z = -z;
            }
        } else {
            if x == 0.0 {
                return x;
            }
            let s = x * x;
            let num = (x * s) * Self::poly(s, &P);
            let mut den = Self::fa(Q[0], x, x); // s + Q0
            den = Self::fa(Q[1], s, den);
            den = Self::fa(Q[2], s, den);
            z = x + num / den;
        }
        z
    }

    // -- cbrt.go / hypot.go --------------------------------------------------

    pub fn cbrt(x: f64) -> f64 {
        const B1: u64 = 715094163;
        const B2: u64 = 696219795;
        const C: f64 = 5.42857142857142815906e-01;
        const D: f64 = -7.05306122448979611050e-01;
        const E: f64 = 1.41428571428571436819e+00;
        const F: f64 = 1.60714285714285720630e+00;
        const G: f64 = 3.57142857142857150787e-01;
        const SMALLEST_NORMAL: f64 = 2.22507385850720138309e-308;
        if x == 0.0 || is_nan(x) || is_inf(x, 0) {
            return x;
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        let mut t = from_bits(bits(x) / 3 + (B1 << 32));
        if x < SMALLEST_NORMAL {
            t = (1u64 << 54) as f64;
            t *= x;
            t = from_bits(bits(t) / 3 + (B2 << 32));
        }
        let mut r = t * t / x;
        let mut s = Self::fa(C, r, t);
        t *= G + F / (s + E + D / s);
        t = from_bits((bits(t) & (0xFFFFFFFFC << 28)) + (1 << 30));
        s = t * t;
        r = x / s;
        let w = t + t;
        r = (r - t) / (w + r);
        t = Self::fa(t, t, r);
        if sign {
            t = -t;
        }
        t
    }

    pub fn hypot(p: f64, q: f64) -> f64 {
        let (mut p, mut q) = (abs(p), abs(q));
        if is_inf(p, 1) || is_inf(q, 1) {
            return inf(1);
        }
        if is_nan(p) || is_nan(q) {
            return nan();
        }
        if p < q {
            std::mem::swap(&mut p, &mut q);
        }
        if p == 0.0 {
            return 0.0;
        }
        q /= p;
        p * sqrt(Self::fa(1.0, q, q))
    }

    // -- erf.go --------------------------------------------------------------

    pub fn erf(x: f64) -> f64 {
        const VERY_TINY: f64 = 2.848094538889218e-306;
        const SMALL: f64 = 1.0 / (1u64 << 28) as f64;
        if is_nan(x) {
            return nan();
        }
        if is_inf(x, 1) {
            return 1.0;
        }
        if is_inf(x, -1) {
            return -1.0;
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        if x < 0.84375 {
            let temp = if x < SMALL {
                if x < VERY_TINY {
                    0.125 * Self::fa(8.0 * x, EFX8, x) // 0.125*(8.0*x + efx8*x)
                } else {
                    Self::fa(x, EFX, x) // x + efx*x
                }
            } else {
                let z = x * x;
                let r = Self::poly(z, &PP);
                let s = Self::poly(z, &QQ);
                let y = r / s;
                Self::fa(x, x, y)
            };
            return if sign { -temp } else { temp };
        }
        if x < 1.25 {
            let s = x - 1.0;
            let p = Self::poly(s, &PA);
            let q = Self::poly(s, &QA);
            if sign {
                return -ERX - p / q;
            }
            return ERX + p / q;
        }
        if x >= 6.0 {
            return if sign { -1.0 } else { 1.0 };
        }
        let s = 1.0 / (x * x);
        let (r, ss) = if x < ERF_ONE_OVER_035 {
            (Self::poly(s, &RA), Self::poly(s, &SA))
        } else {
            (Self::poly(s, &RB), Self::poly(s, &SB))
        };
        let z = from_bits(bits(x) & 0xffffffff00000000);
        let r = Self::exp(Self::fnm(0.5625, z, z)) * Self::exp(Self::fa(r / ss, z - x, z + x));
        if sign {
            return r / x - 1.0;
        }
        1.0 - r / x
    }

    pub fn erfc(x: f64) -> f64 {
        const TINY: f64 = 1.0 / (1u64 << 56) as f64;
        const ONE_PLUS_ERX: f64 = f64::from_bits(0x3ffd8560b0000000);
        const ONE_MINUS_ERX: f64 = f64::from_bits(0x3fc3d4fa80000000);
        if is_nan(x) {
            return nan();
        }
        if is_inf(x, 1) {
            return 0.0;
        }
        if is_inf(x, -1) {
            return 2.0;
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        if x < 0.84375 {
            let temp = if x < TINY {
                x
            } else {
                let z = x * x;
                let r = Self::poly(z, &PP);
                let s = Self::poly(z, &QQ);
                let y = r / s;
                if x < 0.25 {
                    Self::fa(x, x, y)
                } else {
                    0.5 + Self::fa(x - 0.5, x, y)
                }
            };
            if sign {
                return 1.0 + temp;
            }
            return 1.0 - temp;
        }
        if x < 1.25 {
            let s = x - 1.0;
            let p = Self::poly(s, &PA);
            let q = Self::poly(s, &QA);
            if sign {
                return ONE_PLUS_ERX + p / q;
            }
            return ONE_MINUS_ERX - p / q;
        }
        if x < 28.0 {
            let s = 1.0 / (x * x);
            let (r, ss);
            if x < ERF_ONE_OVER_035 {
                r = Self::poly(s, &RA);
                ss = Self::poly(s, &SA);
            } else {
                if sign && x > 6.0 {
                    return 2.0;
                }
                r = Self::poly(s, &RB);
                ss = Self::poly(s, &SB);
            }
            let z = from_bits(bits(x) & 0xffffffff00000000);
            let r = Self::exp(Self::fnm(0.5625, z, z)) * Self::exp(Self::fa(r / ss, z - x, z + x));
            if sign {
                return 2.0 - r / x;
            }
            return r / x;
        }
        if sign {
            return 2.0;
        }
        0.0
    }

    // -- gamma.go ------------------------------------------------------------

    fn stirling(x: f64) -> (f64, f64) {
        const SQRT_TWO_PI: f64 = 2.506628274631000502417;
        const MAX_STIRLING: f64 = 143.01608;
        if x > 200.0 {
            return (inf(1), 1.0);
        }
        let mut w = 1.0 / x;
        w = Self::fa(1.0, w, Self::poly(w, &GAM_S));
        let mut y1 = Self::exp(x);
        let mut y2 = 1.0;
        if x > MAX_STIRLING {
            let v = Self::pow(x, Self::fr(0.25, 0.5, x));
            y2 = v / y1;
            y1 = v;
        } else {
            y1 = Self::pow(x, x - 0.5) / y1;
        }
        (y1, SQRT_TWO_PI * w * y2)
    }

    fn is_neg_int(x: f64) -> bool {
        if x < 0.0 {
            let (_, xf) = Self::modf(x);
            return xf == 0.0;
        }
        false
    }

    pub fn gamma(x: f64) -> f64 {
        const EULER: f64 = 0.57721566490153286060651209008240243104215933593992;
        if Self::is_neg_int(x) || is_inf(x, -1) || is_nan(x) {
            return nan();
        }
        if is_inf(x, 1) {
            return inf(1);
        }
        if x == 0.0 {
            if signbit(x) {
                return inf(-1);
            }
            return inf(1);
        }
        let mut x = x;
        let q = abs(x);
        let mut p = Self::floor(q);
        if q > 33.0 {
            if x >= 0.0 {
                let (y1, y2) = Self::stirling(x);
                return y1 * y2;
            }
            let mut signgam: i64 = 1;
            let ip = p as i64;
            if ip & 1 == 0 {
                signgam = -1;
            }
            let mut z = q - p;
            if z > 0.5 {
                p += 1.0;
                z = q - p;
            }
            z = q * Self::sin(PI * z);
            if z == 0.0 {
                return inf(signgam);
            }
            let (sq1, sq2) = Self::stirling(q);
            let absz = abs(z);
            let d = absz * sq1 * sq2;
            if is_inf(d, 0) {
                z = PI / absz / sq1 / sq2;
            } else {
                z = PI / d;
            }
            return signgam as f64 * z;
        }

        let mut z = 1.0;
        while x >= 3.0 {
            x -= 1.0;
            z *= x;
        }
        let small = 'r: {
            while x < 0.0 {
                if x > -1e-09 {
                    break 'r true;
                }
                z /= x;
                x += 1.0;
            }
            while x < 2.0 {
                if x < 1e-09 {
                    break 'r true;
                }
                z /= x;
                x += 1.0;
            }
            false
        };
        if small {
            if x == 0.0 {
                return inf(1);
            }
            return z / (Self::fa(1.0, EULER, x) * x);
        }
        if x == 2.0 {
            return z;
        }
        x -= 2.0;
        let p = Self::poly(x, &GAM_P);
        let q = Self::poly(x, &GAM_Q);
        z * p / q
    }

    // -- j0.go / j1.go / jn.go -----------------------------------------------

    fn pzero(x: f64) -> f64 {
        let (p, q): (&[f64; 6], &[f64; 5]) = if x >= 8.0 {
            (&P0R8, &P0S8)
        } else if x >= 4.5454 {
            (&P0R5, &P0S5)
        } else if x >= 2.8571 {
            (&P0R3, &P0S3)
        } else {
            (&P0R2, &P0S2)
        };
        let z = 1.0 / (x * x);
        let r = Self::poly(z, &[p[5], p[4], p[3], p[2], p[1], p[0]]);
        let s = Self::poly(z, &[q[4], q[3], q[2], q[1], q[0], 1.0]);
        1.0 + r / s
    }

    fn qzero(x: f64) -> f64 {
        let (p, q): (&[f64; 6], &[f64; 6]) = if x >= 8.0 {
            (&Q0R8, &Q0S8)
        } else if x >= 4.5454 {
            (&Q0R5, &Q0S5)
        } else if x >= 2.8571 {
            (&Q0R3, &Q0S3)
        } else {
            (&Q0R2, &Q0S2)
        };
        let z = 1.0 / (x * x);
        let r = Self::poly(z, &[p[5], p[4], p[3], p[2], p[1], p[0]]);
        let s = Self::poly(z, &[q[5], q[4], q[3], q[2], q[1], q[0], 1.0]);
        (-0.125 + r / s) / x
    }

    fn pone(x: f64) -> f64 {
        let (p, q): (&[f64; 6], &[f64; 5]) = if x >= 8.0 {
            (&P1R8, &P1S8)
        } else if x >= 4.5454 {
            (&P1R5, &P1S5)
        } else if x >= 2.8571 {
            (&P1R3, &P1S3)
        } else {
            (&P1R2, &P1S2)
        };
        let z = 1.0 / (x * x);
        let r = Self::poly(z, &[p[5], p[4], p[3], p[2], p[1], p[0]]);
        let s = Self::poly(z, &[q[4], q[3], q[2], q[1], q[0], 1.0]);
        1.0 + r / s
    }

    fn qone(x: f64) -> f64 {
        let (p, q): (&[f64; 6], &[f64; 6]) = if x >= 8.0 {
            (&Q1R8, &Q1S8)
        } else if x >= 4.5454 {
            (&Q1R5, &Q1S5)
        } else if x >= 2.8571 {
            (&Q1R3, &Q1S3)
        } else {
            (&Q1R2, &Q1S2)
        };
        let z = 1.0 / (x * x);
        let r = Self::poly(z, &[p[5], p[4], p[3], p[2], p[1], p[0]]);
        let s = Self::poly(z, &[q[5], q[4], q[3], q[2], q[1], q[0], 1.0]);
        (0.375 + r / s) / x
    }

    pub fn j0(x: f64) -> f64 {
        const TWO_M27: f64 = 1.0 / (1u64 << 27) as f64;
        const TWO_M13: f64 = 1.0 / (1u64 << 13) as f64;
        const TWO129: f64 = f64::from_bits(0x4800000000000000);
        const R: [f64; 4] = [
            -4.61832688532103189199e-09, // R05
            1.82954049532700665670e-06,  // R04
            -1.89979294238854721751e-04, // R03
            1.56249999999999947958e-02,  // R02
        ];
        const S: [f64; 5] = [
            1.16614003333790000205e-09, // S04
            5.13546550207318111446e-07, // S03
            1.16926784663337450260e-04, // S02
            1.56191029464890010492e-02, // S01
            1.0,
        ];
        if is_nan(x) {
            return x;
        }
        if is_inf(x, 0) {
            return 0.0;
        }
        if x == 0.0 {
            return 1.0;
        }
        let x = abs(x);
        if x >= 2.0 {
            let (s, c) = Self::sincos(x);
            let mut ss = s - c;
            let mut cc = s + c;
            if x < MAX_FLOAT64 / 2.0 {
                let z = -Self::cos(x + x);
                if s * c < 0.0 {
                    cc = z / ss;
                } else {
                    ss = z / cc;
                }
            }
            if x > TWO129 {
                return INV_SQRT_PI * cc / sqrt(x);
            }
            let u = Self::pzero(x);
            let v = Self::qzero(x);
            return INV_SQRT_PI * Self::fs(u * cc, v, ss) / sqrt(x); // u*cc - v*ss
        }
        if x < TWO_M13 {
            if x < TWO_M27 {
                return 1.0;
            }
            return Self::fs(1.0, 0.25 * x, x); // 1 - 0.25*x*x
        }
        let z = x * x;
        let r = z * Self::poly(z, &R);
        let s = Self::poly(z, &S);
        if x < 1.0 {
            return Self::fa(1.0, z, -0.25 + r / s);
        }
        let a = Self::fa(1.0, x, 0.5) * Self::fs(1.0, x, 0.5); // (1+u)*(1-u), u = 0.5*x
        Self::fa(a, z, r / s)
    }

    pub fn y0(x: f64) -> f64 {
        const TWO_M27: f64 = 1.0 / (1u64 << 27) as f64;
        const TWO129: f64 = f64::from_bits(0x4800000000000000);
        const U00: f64 = -7.38042951086872317523e-02;
        const U: [f64; 7] = [
            -3.98205194132103398453e-11, // U06
            1.95590137035022920206e-08,  // U05
            -3.81407053724364161125e-06, // U04
            3.47453432093683650238e-04,  // U03
            -1.38185671945596898896e-02, // U02
            1.76666452509181115538e-01,  // U01
            U00,
        ];
        const V: [f64; 5] = [
            4.41110311332675467403e-10, // V04
            2.59150851840457805467e-07, // V03
            7.60068627350353253702e-05, // V02
            1.27304834834123699328e-02, // V01
            1.0,
        ];
        if x < 0.0 || is_nan(x) {
            return nan();
        }
        if is_inf(x, 1) {
            return 0.0;
        }
        if x == 0.0 {
            return inf(-1);
        }
        if x >= 2.0 {
            let (s, c) = Self::sincos(x);
            let mut ss = s - c;
            let mut cc = s + c;
            if x < MAX_FLOAT64 / 2.0 {
                let z = -Self::cos(x + x);
                if s * c < 0.0 {
                    cc = z / ss;
                } else {
                    ss = z / cc;
                }
            }
            if x > TWO129 {
                return INV_SQRT_PI * ss / sqrt(x);
            }
            let u = Self::pzero(x);
            let v = Self::qzero(x);
            return INV_SQRT_PI * Self::fa(u * ss, v, cc) / sqrt(x); // u*ss + v*cc
        }
        if x <= TWO_M27 {
            return Self::fa(U00, Self::log(x), TWO_OVER_PI); // U00 + (2/Pi)*Log(x)
        }
        let z = x * x;
        let u = Self::poly(z, &U);
        let v = Self::poly(z, &V);
        let a = TWO_OVER_PI * Self::j0(x);
        Self::fa(u / v, a, Self::log(x)) // u/v + (2/Pi)*J0(x)*Log(x)
    }

    pub fn j1(x: f64) -> f64 {
        const TWO_M27: f64 = 1.0 / (1u64 << 27) as f64;
        const TWO129: f64 = f64::from_bits(0x4800000000000000);
        const R: [f64; 4] = [
            4.96727999609584448412e-08,  // R03
            -1.59955631084035597520e-05, // R02
            1.40705666955189706048e-03,  // R01
            -6.25000000000000000000e-02, // R00
        ];
        const S: [f64; 6] = [
            1.23542274426137913908e-11, // S05
            5.04636257076217042715e-09, // S04
            1.17718464042623683263e-06, // S03
            1.85946785588630915560e-04, // S02
            1.91537599538363460805e-02, // S01
            1.0,
        ];
        if is_nan(x) {
            return x;
        }
        if is_inf(x, 0) || x == 0.0 {
            return 0.0;
        }
        let mut sign = false;
        let mut x = x;
        if x < 0.0 {
            x = -x;
            sign = true;
        }
        if x >= 2.0 {
            let (s, c) = Self::sincos(x);
            let mut ss = -s - c;
            let mut cc = s - c;
            if x < MAX_FLOAT64 / 2.0 {
                let z = Self::cos(x + x);
                if s * c > 0.0 {
                    cc = z / ss;
                } else {
                    ss = z / cc;
                }
            }
            let z = if x > TWO129 {
                INV_SQRT_PI * cc / sqrt(x)
            } else {
                let u = Self::pone(x);
                let v = Self::qone(x);
                INV_SQRT_PI * Self::fs(u * cc, v, ss) / sqrt(x) // u*cc - v*ss
            };
            return if sign { -z } else { z };
        }
        if x < TWO_M27 {
            return 0.5 * x;
        }
        let z = x * x;
        let mut r = z * Self::poly(z, &R);
        let s = Self::poly(z, &S);
        r *= x;
        let z = Self::fa(r / s, 0.5, x); // 0.5*x + r/s
        if sign {
            -z
        } else {
            z
        }
    }

    pub fn y1(x: f64) -> f64 {
        const TWO_M54: f64 = 1.0 / (1u64 << 54) as f64;
        const TWO129: f64 = f64::from_bits(0x4800000000000000);
        const U: [f64; 5] = [
            -9.19099158039878874504e-08, // U04
            2.35252600561610495928e-05,  // U03
            -1.91256895875763547298e-03, // U02
            5.04438716639811282616e-02,  // U01
            -1.96057090646238940668e-01, // U00
        ];
        const V: [f64; 6] = [
            1.66559246207992079114e-11, // V04
            6.22741452364621501295e-09, // V03
            1.35608801097516229404e-06, // V02
            2.02552581025135171496e-04, // V01
            1.99167318236649903973e-02, // V00
            1.0,
        ];
        if x < 0.0 || is_nan(x) {
            return nan();
        }
        if is_inf(x, 1) {
            return 0.0;
        }
        if x == 0.0 {
            return inf(-1);
        }
        if x >= 2.0 {
            let (s, c) = Self::sincos(x);
            let mut ss = -s - c;
            let mut cc = s - c;
            if x < MAX_FLOAT64 / 2.0 {
                let z = Self::cos(x + x);
                if s * c > 0.0 {
                    cc = z / ss;
                } else {
                    ss = z / cc;
                }
            }
            if x > TWO129 {
                return INV_SQRT_PI * ss / sqrt(x);
            }
            let u = Self::pone(x);
            let v = Self::qone(x);
            return INV_SQRT_PI * Self::fa(v * cc, u, ss) / sqrt(x); // u*ss + v*cc
        }
        if x <= TWO_M54 {
            return -TWO_OVER_PI / x;
        }
        let z = x * x;
        let u = Self::poly(z, &U);
        let v = Self::poly(z, &V);
        let b = TWO_OVER_PI * Self::fr(1.0 / x, Self::j1(x), Self::log(x)); // (2/Pi)*(J1*Log - 1/x)
        Self::fa(b, x, u / v) // x*(u/v) + b
    }

    pub fn jn(n: i64, x: f64) -> f64 {
        const TWO_M29: f64 = 1.0 / (1u64 << 29) as f64;
        const TWO302: f64 = f64::from_bits(0x52D0000000000000);
        if is_nan(x) {
            return x;
        }
        if is_inf(x, 0) {
            return 0.0;
        }
        if n == 0 {
            return Self::j0(x);
        }
        if x == 0.0 {
            return 0.0;
        }
        let (mut n, mut x) = (n, x);
        if n < 0 {
            n = n.wrapping_neg();
            x = -x;
        }
        if n == 1 {
            return Self::j1(x);
        }
        let mut sign = false;
        if x < 0.0 {
            x = -x;
            if n & 1 == 1 {
                sign = true;
            }
        }
        let mut b;
        if n as f64 <= x {
            if x >= TWO302 {
                let (s, c) = Self::sincos(x);
                let temp = match n & 3 {
                    0 => c + s,
                    1 => -c + s,
                    2 => -c - s,
                    _ => c - s,
                };
                b = INV_SQRT_PI * temp / sqrt(x);
            } else {
                b = Self::j1(x);
                let mut a = Self::j0(x);
                let mut i: i64 = 1;
                while i < n {
                    let nb = Self::fr(a, b, i.wrapping_add(i) as f64 / x);
                    a = b;
                    b = nb;
                    i += 1;
                }
            }
        } else if x < TWO_M29 {
            if n > 33 {
                b = 0.0;
            } else {
                let temp = x * 0.5;
                b = temp;
                let mut a = 1.0;
                let mut i = 2;
                while i <= n {
                    a *= i as f64;
                    b *= temp;
                    i += 1;
                }
                b /= a;
            }
        } else {
            let w = n.wrapping_add(n) as f64 / x;
            let h = 2.0 / x;
            let mut q0 = w;
            let mut z = w + h;
            let mut q1 = Self::fr(1.0, w, z);
            let mut k: i64 = 1;
            while q1 < 1e9 {
                k += 1;
                z += h;
                let nq = Self::fr(q0, z, q1);
                q0 = q1;
                q1 = nq;
            }
            let m = n.wrapping_add(n);
            let mut t = 0.0;
            let mut i = n.wrapping_add(k).wrapping_mul(2);
            while i >= m {
                t = 1.0 / (i as f64 / x - t);
                i -= 2;
            }
            let mut a = t;
            b = 1.0;
            let mut tmp = n as f64;
            let v = 2.0 / x;
            tmp *= Self::log(abs(v * tmp));
            if tmp < 7.09782712893383973096e+02 {
                let mut i = n - 1;
                while i > 0 {
                    let di = i.wrapping_add(i) as f64;
                    let nb = b * di / x - a;
                    a = b;
                    b = nb;
                    i -= 1;
                }
            } else {
                let mut i = n - 1;
                while i > 0 {
                    let di = i.wrapping_add(i) as f64;
                    let nb = b * di / x - a;
                    a = b;
                    b = nb;
                    if b > 1e100 {
                        a /= b;
                        t /= b;
                        b = 1.0;
                    }
                    i -= 1;
                }
            }
            b = t * Self::j0(x) / b;
        }
        if sign {
            -b
        } else {
            b
        }
    }

    pub fn yn(n: i64, x: f64) -> f64 {
        const TWO302: f64 = f64::from_bits(0x52D0000000000000);
        if x < 0.0 || is_nan(x) {
            return nan();
        }
        if is_inf(x, 1) {
            return 0.0;
        }
        if n == 0 {
            return Self::y0(x);
        }
        if x == 0.0 {
            if n < 0 && n & 1 == 1 {
                return inf(1);
            }
            return inf(-1);
        }
        let mut n = n;
        let mut sign = false;
        if n < 0 {
            n = n.wrapping_neg();
            if n & 1 == 1 {
                sign = true;
            }
        }
        if n == 1 {
            if sign {
                return -Self::y1(x);
            }
            return Self::y1(x);
        }
        let mut b;
        if x >= TWO302 {
            let (s, c) = Self::sincos(x);
            let temp = match n & 3 {
                0 => s - c,
                1 => -s - c,
                2 => -s + c,
                _ => s + c,
            };
            b = INV_SQRT_PI * temp / sqrt(x);
        } else {
            let mut a = Self::y0(x);
            b = Self::y1(x);
            let mut i: i64 = 1;
            while i < n && !is_inf(b, -1) {
                let nb = Self::fr(a, i.wrapping_add(i) as f64 / x, b);
                a = b;
                b = nb;
                i += 1;
            }
        }
        if sign {
            -b
        } else {
            b
        }
    }
}

