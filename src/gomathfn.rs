//! Bit-exact port of Go 1.25's `math` package (the functions Tengo's `math`
//! module wraps). Depends only on `std`.
//!
//! Every function is a line-by-line port of the pure-Go source in
//! `$GOROOT/src/math`. Two things make Go's results platform dependent, and
//! both are modelled here so the port can reproduce a given platform exactly:
//!
//! * **FMA fusion.** The Go compiler fuses `x*y + z` / `x*y - z` / `z - x*y`
//!   into one fused multiply-add on arm64 (also ppc64x, s390x, riscv64,
//!   loong64), never on amd64/386. Each such site below goes through
//!   `fa`/`fs`/`fr`/`fnm`; the operand chosen at every site was read off the
//!   arm64 code generated by go1.25 (`go build -gcflags=math=-S`). With
//!   `FMA = false` they evaluate as separately rounded `*` and `+`.
//! * **Assembly.** On arm64 `Exp` and `Exp2` are written in assembly
//!   (`exp_arm64.s`), which rounds differently from `exp.go`. `ASM = true`
//!   emulates that assembly; `ASM = false` uses the pure-Go `exp.go` code.
//!   (Floor/Ceil/Trunc/Modf/Max/Min are also assembly on arm64 but give the
//!   same results as the pure-Go code; Log and Hypot are pure Go on arm64.)
//!
//! `GoMath<true, true>` is Go on linux/arm64; `GoMath<true, false>` is the
//! pure-Go source compiled for arm64; `GoMath<false, false>` is the pure-Go
//! source without fusion (Go on amd64, except that amd64 uses assembly for
//! Exp, Log and Hypot, which this file does not emulate). The free functions
//! use [`Go`], selected by [`FMA`] and [`ARM64_ASM`].
#![allow(clippy::excessive_precision, clippy::many_single_char_names, clippy::too_many_lines)]
#![allow(dead_code)]

/// Fuse multiply-adds the way the Go compiler does on arm64.
pub const FMA: bool = true;
/// Use the arm64 assembly versions of Exp and Exp2.
pub const ARM64_ASM: bool = true;

/// The configuration used by the free functions in this module.
pub type Go = GoMath<FMA, ARM64_ASM>;
/// Go on linux/arm64 (fused, assembly Exp/Exp2).
pub type GoArm64 = GoMath<true, true>;
/// The pure-Go source as compiled for arm64 (fused, `exp.go`).
pub type GoPureFused = GoMath<true, false>;
/// The pure-Go source without fusion.
pub type GoPure = GoMath<false, false>;

/// Go's math package under one evaluation model. See the module docs.
pub struct GoMath<const FMA: bool, const ASM: bool>;

